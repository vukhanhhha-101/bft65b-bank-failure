"""PART 2a - automated data-quality report -> reports/dq_report.md"""
import json
import polars as pl
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
from config import *


def main():
    df = scan_panel().collect()
    fails = pl.read_parquet(PROC / "failures.parquet")
    inst = pl.read_parquet(PROC / "institutions.parquet")
    out = ["# Data-quality report (auto-generated by src/03_quality.py)\n"]

    # 1. completeness vs API totals
    man = json.loads((RAW / "manifest_financials.json").read_text())
    man_df = pl.DataFrame({"REPDTE": [dt.datetime.strptime(k, "%Y%m%d").date() for k in man],
                           "api_total": [v["api_total"] for v in man.values()]})
    per_q = df.group_by("REPDTE").len().sort("REPDTE").join(man_df, on="REPDTE", how="full", coalesce=True)
    bad = per_q.filter(pl.col("len") != pl.col("api_total"))
    out += ["## 1. Completeness", f"- quarters: {per_q.height}; rows: {df.height:,}; banks: {df['CERT'].n_unique():,}",
            f"- quarters whose row count != API total: {bad.height}"]
    n_dup = df.height - df.select(["CERT", "REPDTE"]).unique().height
    out.append(f"- duplicate (CERT, REPDTE): {n_dup}\n")

    # 2. missingness by decade
    dec = df.with_columns(((pl.col("REPDTE").dt.year() // 10) * 10).alias("decade"))
    miss = dec.group_by("decade").agg([pl.col(c).is_null().mean().alias(c) for c in NUMERIC]).sort("decade")
    mt = miss.drop("decade").transpose(include_header=True, header_name="field",
                                       column_names=[f"{d}s" for d in miss["decade"]])
    out += ["## 2. Share of missing values by decade", md(mt, 60), ""]

    # 3. validity rules
    A = pl.col
    rules = {
        "ASSET null or <= 0": A("ASSET").is_null() | (A("ASSET") <= 0),
        "DEP > ASSET": A("DEP") > A("ASSET"),
        "DEPDOM > DEP": A("DEPDOM") > A("DEP"),
        "EQ < 0 (negative equity)": A("EQ") < 0,
        "EQ > ASSET": A("EQ") > A("ASSET"),
        "LNLSNET > ASSET": A("LNLSNET") > A("ASSET"),
        "LNLSGR < 0": A("LNLSGR") < 0,
        "NCLNLS < 0": A("NCLNLS") < 0,
        "NCLNLS > LNLSGR": A("NCLNLS") > A("LNLSGR"),
        "LNATRES < 0": A("LNATRES") < 0,
        "ROA outside [-100, 100]": ~A("ROA").is_between(-100, 100),
        "RBC1AAJ outside [-100, 200]": ~A("RBC1AAJ").is_between(-100, 200),
    }
    cnt = df.select([r.sum().alias(k) for k, r in rules.items()]).row(0)
    vt = pl.DataFrame({"rule": list(rules), "n_rows": [int(x or 0) for x in cnt]}).with_columns(
        (pl.col("n_rows") / df.height * 100).alias("pct"))
    out += ["## 3. Rule violations", md(vt), ""]

    # 4. year-to-date check
    ytd = (df.filter(A("NETINC").is_not_null() & (A("ASSET") > 0) & A("REPDTE").dt.year().is_between(2010, 2019))
             .group_by(A("REPDTE").dt.month().alias("month"))
             .agg((A("NETINC") / A("ASSET")).median().alias("median_NETINC_over_ASSET")).sort("month"))
    out += ["## 4. Are flow variables year-to-date? (rises Mar->Dec = YES, must be de-cumulated)", md(ytd), ""]

    # 5. gaps in the quarterly sequence
    g = (df.with_columns(QIDX).group_by("CERT").agg(n=pl.len(), first=A("qidx").min(), last=A("qidx").max())
           .with_columns((A("last") - A("first") + 1 - A("n")).alias("missing_q")))
    out += ["## 5. Banks with gaps in their quarterly history",
            f"- banks with >=1 missing quarter: {g.filter(A('missing_q') > 0).height:,} of {g.height:,}",
            f"- total missing bank-quarters: {int(g['missing_q'].sum()):,}\n"]

    # 6. outliers
    rows = []
    for c in ["ROA", "ROE", "NIMY", "RBC1AAJ", "RBCRWAJ", "NCLNLS", "LNATRES", "ASSET"]:
        s = df[c].drop_nulls()
        rows.append([c, s.min()] + [s.quantile(q) for q in (0.001, 0.01, 0.5, 0.99, 0.999)] + [s.max()])
    out += ["## 6. Distribution tails",
            md(pl.DataFrame(rows, schema=["field", "min", "p0.1", "p1", "p50", "p99", "p99.9", "max"], orient="row")), ""]


    A = pl.col

    # 7. Exits: separate FAILURE from ASSISTANCE
    last = df.group_by("CERT").agg(
        A("REPDTE").max().alias("LAST")
    )
    maxd = df["REPDTE"].max()

    failure_rows = fails.filter(
        (A("RESTYPE") == "FAILURE") &
        A("CERT").is_not_null()
    )
    assistance_rows = fails.filter(
        A("RESTYPE") == "ASSISTANCE"
    )

    failure_by_cert = failure_rows.group_by("CERT").agg(
        A("FAILDATE").min().alias("FAILDATE"),
        pl.len().alias("failure_records")
    )

    ex = (
        last.join(failure_by_cert, on="CERT", how="left")
        .join(
            inst.select(["CERT", "ACTIVE", "CHANGEC1", "ENDEFYMD"]),
            on="CERT",
            how="left"
        )
        .with_columns(
            pl.when(A("failure_records").is_not_null())
            .then(pl.lit("failure"))
            .when(A("LAST") < maxd)
            .then(pl.lit("other_exit"))
            .otherwise(pl.lit("active"))
            .alias("exit_type")
        )
    )

    out += [
        "## 7. Exits (failure vs other)",
        md(ex.group_by("exit_type").len().sort("len")),
        "",
        "Other exits by CHANGEC1 (map codes with the FDIC dictionary; mergers are NOT failures):",
        md(ex.filter(A("exit_type") == "other_exit").group_by("CHANGEC1").len().sort("len", descending=True), 15),
        "",
        "Failures table by RESTYPE:",
        md(fails.group_by("RESTYPE").len().sort("len", descending=True)),
        "",
        "## 8. Failures table audit (CERT linkage & repeated events)",
        f"- total raw records in Failures table: {fails.height:,}",
        f"- records missing CERT (kept in raw table, excluded from bank-level join): {fails.filter(A('CERT').is_null()).height:,} "
        f"(FAILURE: {fails.filter(A('CERT').is_null() & (A('RESTYPE') == 'FAILURE')).height:,}, "
        f"ASSISTANCE: {fails.filter(A('CERT').is_null() & (A('RESTYPE') == 'ASSISTANCE')).height:,})",
        f"- valid FAILURE records with non-null CERT: {failure_rows.height:,}",
        f"- distinct failed banks (unique CERT with >=1 FAILURE record): {failure_by_cert.height:,}",
        f"- ASSISTANCE records in raw table: {assistance_rows.height:,} "
        f"(with valid CERT: {assistance_rows.filter(A('CERT').is_not_null()).height:,} across {assistance_rows.filter(A('CERT').is_not_null())['CERT'].n_unique():,} distinct CERTs)",
        "",
    ]

    nopanel = failure_by_cert.join(last, on="CERT", how="anti").height
    inpanel = failure_by_cert.join(last, on="CERT")
    after = inpanel.filter(A("LAST") >= A("FAILDATE")).height
    gap = inpanel.select((A("FAILDATE") - A("LAST")).dt.total_days().alias("d"))["d"].drop_nulls()
    out += [
        f"- distinct FAILURE banks (valid CERT) with no Financials rows: {nopanel}",
        f"- distinct FAILURE banks whose last report is dated on/after FAILDATE (impossible for point-in-time): {after}",
        f"- days between last report and FAILDATE (distinct FAILURE banks in panel): median {gap.median():.0f}, p10 {gap.quantile(0.1):.0f}, p90 {gap.quantile(0.9):.0f}\n",
    ]

    (REPORTS / "dq_report.md").write_text("\n".join(out), encoding="utf-8")
    fig, ax = plt.subplots(1, 2, figsize=(11, 3.5))
    fy = (
        fails.filter(
            (A("RESTYPE") == "FAILURE") &
            A("FAILDATE").is_not_null()
        )
        .group_by(A("FAILDATE").dt.year().alias("yr"))
        .len()
        .sort("yr")
    )
    ax[0].bar(fy["yr"], fy["len"]); ax[0].set_title("Failure records per year")
    ax[1].plot(per_q["REPDTE"], per_q["len"]); ax[1].set_title("Reporting banks per quarter")
    plt.tight_layout(); plt.savefig(REPORTS / "dq_overview.png", dpi=150)
    print("\n".join(out))


if __name__ == "__main__":
    main()
