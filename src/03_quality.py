"""PART 2a - automated data-quality report -> reports/dq_report.md

This script audits the cleaned Financials panel and FDIC small tables.
It does not delete or modify source records.

Failure classification:
- A bank is a failure only if it has at least one RESTYPE == "FAILURE"
  record with a non-null CERT.
- ASSISTANCE-only records are not failures.
- For a bank with multiple FAILURE records, the earliest FAILDATE is used
  as its first failure date for bank-level linkage.
- Missing-CERT records remain in the raw table and are reported separately.
"""
import json
import math

import polars as pl
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from config import *


def _fmt(value, digits=0):
    """Format nullable numeric statistics safely for Markdown."""
    if value is None:
        return "n/a"
    try:
        value = float(value)
    except (TypeError, ValueError):
        return str(value)
    if math.isnan(value):
        return "n/a"
    return f"{value:.{digits}f}"


def main():
    df = scan_panel().collect()
    fails = pl.read_parquet(PROC / "failures.parquet")
    inst = pl.read_parquet(PROC / "institutions.parquet")
    out = ["# Data-quality report (auto-generated by src/03_quality.py)\n"]

    # 1. Completeness vs API totals
    man = json.loads((RAW / "manifest_financials.json").read_text())
    man_df = pl.DataFrame({
        "REPDTE": [
            dt.datetime.strptime(k, "%Y%m%d").date()
            for k in man
        ],
        "api_total": [v["api_total"] for v in man.values()]
    })
    per_q = (
        df.group_by("REPDTE")
        .len()
        .sort("REPDTE")
        .join(man_df, on="REPDTE", how="full", coalesce=True)
    )
    bad = per_q.filter(pl.col("len") != pl.col("api_total"))
    out += [
        "## 1. Completeness",
        f"- quarters: {per_q.height}; rows: {df.height:,}; "
        f"banks: {df['CERT'].n_unique():,}",
        f"- quarters whose row count != API total: {bad.height}"
    ]
    n_dup = df.height - df.select(
        ["CERT", "REPDTE"]
    ).unique().height
    out.append(f"- duplicate (CERT, REPDTE): {n_dup}\n")

    # 2. Missingness by decade
    dec = df.with_columns(
        ((pl.col("REPDTE").dt.year() // 10) * 10).alias("decade")
    )
    miss = (
        dec.group_by("decade")
        .agg([pl.col(c).is_null().mean().alias(c) for c in NUMERIC])
        .sort("decade")
    )
    mt = miss.drop("decade").transpose(
        include_header=True,
        header_name="field",
        column_names=[f"{d}s" for d in miss["decade"]]
    )
    out += [
        "## 2. Share of missing values by decade",
        md(mt, 60),
        ""
    ]

    # 3. Validity rules
    A = pl.col
    rules = {
        "ASSET null or <= 0": A("ASSET").is_null() | (A("ASSET") <= 0),
        "DEP > ASSET": A("DEP") > A("ASSET"),
        "DEPDOM > DEP": A("DEPDOM") > A("DEP"),
        "EQ < 0 (negative equity)": A("EQ") < 0,
        "EQ > ASSET": A("EQ") > A("ASSET"),
        "LNLSNET > ASSET": A("LNLSNET") > A("ASSET"),
        "LNLSGR < 0": A("LNLSGR") < 0,
        "NCLNLS < 0": A("NCLNLS") < 0,
        "NCLNLS > LNLSGR": A("NCLNLS") > A("LNLSGR"),
        "LNATRES < 0": A("LNATRES") < 0,
        "ROA outside [-100, 100]": ~A("ROA").is_between(-100, 100),
        "RBC1AAJ outside [-100, 200]": ~A("RBC1AAJ").is_between(-100, 200),
    }
    cnt = df.select([r.sum().alias(k) for k, r in rules.items()]).row(0)
    vt = pl.DataFrame({
        "rule": list(rules),
        "n_rows": [int(x or 0) for x in cnt]
    }).with_columns(
        (pl.col("n_rows") / max(df.height, 1) * 100).alias("pct")
    )
    out += ["## 3. Rule violations", md(vt), ""]

    # 4. Year-to-date check
    ytd = (
        df.filter(
            A("NETINC").is_not_null()
            & (A("ASSET") > 0)
            & A("REPDTE").dt.year().is_between(2010, 2019)
        )
        .group_by(A("REPDTE").dt.month().alias("month"))
        .agg(
            (A("NETINC") / A("ASSET"))
            .median()
            .alias("median_NETINC_over_ASSET")
        )
        .sort("month")
    )
    out += [
        "## 4. Are flow variables year-to-date? "
        "(rises Mar->Dec = YES, must be de-cumulated)",
        md(ytd),
        ""
    ]

    # 5. Gaps in the quarterly sequence
    g = (
        df.with_columns(QIDX)
        .group_by("CERT")
        .agg(
            n=pl.len(),
            first=A("qidx").min(),
            last=A("qidx").max()
        )
        .with_columns(
            (A("last") - A("first") + 1 - A("n")).alias("missing_q")
        )
    )
    out += [
        "## 5. Banks with gaps in their quarterly history",
        f"- banks with >=1 missing quarter: "
        f"{g.filter(A('missing_q') > 0).height:,} of {g.height:,}",
        f"- total missing bank-quarters: {int(g['missing_q'].sum() or 0):,}\n"
    ]

    # 6. Outliers
    rows = []
    for c in [
        "ROA", "ROE", "NIMY", "RBC1AAJ",
        "RBCRWAJ", "NCLNLS", "LNATRES", "ASSET"
    ]:
        s = df[c].drop_nulls()
        rows.append(
            [c, s.min()]
            + [s.quantile(q) for q in (0.001, 0.01, 0.5, 0.99, 0.999)]
            + [s.max()]
        )
    out += [
        "## 6. Distribution tails",
        md(pl.DataFrame(
            rows,
            schema=[
                "field", "min", "p0.1", "p1", "p50",
                "p99", "p99.9", "max"
            ],
            orient="row"
        )),
        ""
    ]

    # 7. Reporting status and failure linkage.
    # This is a reporting-status proxy, NOT a legal closure classification.
    # A bank is a failure only when it has a valid-CERT FAILURE event.
    last = df.group_by("CERT").agg(
        A("REPDTE").max().alias("LAST")
    )
    maxd = df["REPDTE"].max()

    valid_cert_events = fails.filter(A("CERT").is_not_null())
    failure_rows = valid_cert_events.filter(A("RESTYPE") == "FAILURE")

    # Earliest recorded FAILURE date per bank; ASSISTANCE does not define failure.
    failure_by_cert = failure_rows.group_by("CERT").agg(
        A("FAILDATE").min().alias("FAILDATE"),
        pl.len().alias("failure_records")
    )

    # One institution row per CERT to avoid multiplying bank counts on join.
    inst_lookup = (
        inst.select(["CERT", "ACTIVE", "CHANGEC1", "ENDEFYMD"])
        .unique(subset=["CERT"], keep="first")
    )

    ex = (
        last.join(failure_by_cert, on="CERT", how="left")
        .join(inst_lookup, on="CERT", how="left")
        .with_columns(
            pl.when(A("failure_records").is_not_null())
            .then(pl.lit("failure"))
            .when(A("LAST") == maxd)
            .then(pl.lit("reporting_in_latest_quarter"))
            .otherwise(pl.lit("not_reporting_in_latest_quarter"))
            .alias("reporting_status")
        )
    )

    out += [
        "## 7. Failure and reporting status",
        "A bank is classified as failure only if it has at least one valid-CERT "
        "record with RESTYPE = FAILURE. ASSISTANCE-only records are not failures.",
        "For non-failure banks, reporting status indicates whether a Financials "
        "record exists in the latest quarter in this dataset. It is NOT evidence "
        "of legal closure, insolvency, or active regulatory status.",
        md(ex.group_by("reporting_status").len().sort("len")),
        "",
        "Non-failure banks not reporting in the latest quarter, by CHANGEC1 "
        "(codes require interpretation using the FDIC field dictionary):",
        md(
            ex.filter(A("reporting_status") == "not_reporting_in_latest_quarter")
            .group_by("CHANGEC1")
            .len()
            .sort("len", descending=True),
            15
        ),
        "",
        "Failures table by RESTYPE:",
        md(fails.group_by("RESTYPE").len().sort("len", descending=True)),
        ""
    ]

    # Distinct failure-bank linkage to Financials.
    panel_certs = last.select("CERT")
    no_panel = failure_by_cert.join(
        panel_certs, on="CERT", how="anti"
    ).height

    failure_with_last = failure_by_cert.join(
        last, on="CERT", how="inner"
    )

    # Diagnostic only: last observed report on/after first failure date.
    # This is not the pre-failure information date used for modelling.
    last_report_on_after_failure = failure_with_last.filter(
        A("FAILDATE").is_not_null() & (A("LAST") >= A("FAILDATE"))
    ).height

    # Correct pre-failure reporting gap: latest REPDTE strictly BEFORE FAILDATE.
    # A report dated on the failure date is excluded to avoid same-day look-ahead.
    pre_failure_reports = (
        df.join(
            failure_by_cert.select(["CERT", "FAILDATE"]),
            on="CERT",
            how="inner"
        )
        .filter(
            A("FAILDATE").is_not_null()
            & A("REPDTE").is_not_null()
            & (A("REPDTE") < A("FAILDATE"))
        )
        .group_by("CERT")
        .agg(A("REPDTE").max().alias("LAST_REPORT_BEFORE_FAILURE"))
    )

    pre_failure_gap = (
        failure_by_cert.select(["CERT", "FAILDATE"])
        .join(pre_failure_reports, on="CERT", how="inner")
        .select(
            (A("FAILDATE") - A("LAST_REPORT_BEFORE_FAILURE"))
            .dt.total_days()
            .alias("days")
        )["days"]
        .drop_nulls()
    )

    out += [
        f"- distinct valid-CERT failure banks: {failure_by_cert.height:,}",
        f"- distinct failure banks with no Financials rows: {no_panel:,}",
        f"- failure banks whose last observed report is on/after FAILDATE "
        f"(diagnostic only): {last_report_on_after_failure:,}",
        f"- failure banks with a Financials report strictly before FAILDATE: "
        f"{len(pre_failure_gap):,}",
        f"- pre-failure gap in days (latest REPDTE < FAILDATE): "
        f"median {_fmt(pre_failure_gap.median())}, "
        f"p10 {_fmt(pre_failure_gap.quantile(0.1))}, "
        f"p90 {_fmt(pre_failure_gap.quantile(0.9))}\n"
    ]

    # 8. Failures-table identifier and duplicate diagnostics.
    missing_cert = fails.filter(A("CERT").is_null())
    missing_by_type = (
        missing_cert.group_by("RESTYPE")
        .len()
        .sort("len", descending=True)
    )

    cert_frequency = (
        valid_cert_events.group_by("CERT")
        .agg(pl.len().alias("records"))
    )
    repeated_cert = cert_frequency.filter(A("records") > 1)

    repeated_detail = (
        valid_cert_events.group_by("CERT")
        .agg(
            pl.len().alias("records"),
            A("FAILDATE").n_unique().alias("distinct_faildates"),
            A("RESTYPE").n_unique().alias("distinct_restypes")
        )
        .filter(A("records") > 1)
    )

    overlap = repeated_detail.filter(
        (A("distinct_restypes") > 1)
    )

    event_key_duplicates = int(
        valid_cert_events
        .select(["CERT", "FAILDATE", "RESTYPE"])
        .is_duplicated()
        .sum()
    )
    exact_duplicates = int(fails.is_duplicated().sum())
    duplicate_extra_rows = (
        valid_cert_events.height - valid_cert_events["CERT"].n_unique()
    )

    out += [
        "## 8. Failures-table data quality",
        f"- total raw records: {fails.height:,}",
        f"- FAILURE records: {fails.filter(A('RESTYPE') == 'FAILURE').height:,}",
        f"- ASSISTANCE records: {fails.filter(A('RESTYPE') == 'ASSISTANCE').height:,}",
        f"- records with missing CERT: {missing_cert.height:,}",
        f"- missing CERT by RESTYPE:\n{md(missing_by_type)}",
        f"- distinct valid CERT: {valid_cert_events['CERT'].n_unique():,}",
        f"- CERT groups with multiple records: {repeated_cert.height:,}",
        f"- extra rows beyond one record per CERT: {duplicate_extra_rows:,}",
        f"- repeated CERT groups with multiple FAILDATE values: "
        f"{repeated_detail.filter(A('distinct_faildates') > 1).height:,}",
        f"- repeated CERT groups with multiple RESTYPE values: {overlap.height:,}",
        f"- duplicate event-key rows (CERT, FAILDATE, RESTYPE): "
        f"{event_key_duplicates:,}",
        f"- exact duplicate rows: {exact_duplicates:,}",
        "Repeated CERTs are retained: multiple dates or event types "
        "represent distinct event records, not automatically duplicate data.",
        "Missing-CERT records are retained in the raw table but cannot "
        "be linked to a bank-level Financials panel.",
        ""
    ]

    (REPORTS / "dq_report.md").write_text(
        "\n".join(out),
        encoding="utf-8"
    )

    # Plot actual FAILURE event records by year. Missing CERT events
    # remain included because they are still FAILURE records.
    fig, ax = plt.subplots(1, 2, figsize=(11, 3.5))
    fy = (
        fails.filter(
            (A("RESTYPE") == "FAILURE")
            & A("FAILDATE").is_not_null()
        )
        .group_by(A("FAILDATE").dt.year().alias("yr"))
        .len()
        .sort("yr")
    )
    ax[0].bar(fy["yr"], fy["len"])
    ax[0].set_title("Failure records per year")

    ax[1].plot(per_q["REPDTE"], per_q["len"])
    ax[1].set_title("Reporting banks per quarter")

    plt.tight_layout()
    plt.savefig(REPORTS / "dq_overview.png", dpi=150)
    plt.close(fig)

    print("\n".join(out))


if __name__ == "__main__":
    main()
